        GameObject msgObj = new GameObject("MessageText");
        msgObj.transform.SetParent(panelRoot.transform, false);
        var msgRect = msgObj.AddComponent<RectTransform>();
        msgRect.anchorMin = new Vector2(0.1f, 0.18f);
        msgRect.anchorMax = new Vector2(0.9f, 0.32f);
        msgRect.offsetMin = Vector2.zero;
        msgRect.offsetMax = Vector2.zero;

        messageText = msgObj.AddComponent<TextMeshProUGUI>();
        messageText.alignment = TextAlignmentOptions.Center;
