    {
        // 1. Panel nền tối
        panelRoot = new GameObject("EvolutionPanel");
        panelRoot.transform.SetParent(transform, false);
        var panelRect = panelRoot.AddComponent<RectTransform>();
        panelRect.anchorMin = Vector2.zero;
        panelRect.anchorMax = Vector2.one;
        panelRect.offsetMin = Vector2.zero;
        panelRect.offsetMax = Vector2.zero;

        var bgImage = panelRoot.AddComponent<Image>();
        bgImage.color = new Color(0.04f, 0.04f, 0.08f, 0.96f); // Nền tối huyền ảo
        panelCanvasGroup = panelRoot.AddComponent<CanvasGroup>();

        // 2. Title Text
        GameObject titleObj = new GameObject("TitleText");
        titleObj.transform.SetParent(panelRoot.transform, false);
        var titleRect = titleObj.AddComponent<RectTransform>();
        titleRect.anchorMin = new Vector2(0.1f, 0.78f);
        titleRect.anchorMax = new Vector2(0.9f, 0.92f);
        titleRect.offsetMin = Vector2.zero;
        titleRect.offsetMax = Vector2.zero;

        titleText = titleObj.AddComponent<TextMeshProUGUI>();
        titleText.alignment = TextAlignmentOptions.Center;
        titleText.fontSize = 42;
        titleText.fontStyle = FontStyles.Bold;
        titleText.color = new Color(1f, 0.95f, 0.6f); // Vàng ánh kim

        // 3. Center Container cho Beast
        GameObject centerObj = new GameObject("BeastCenter");
        centerObj.transform.SetParent(panelRoot.transform, false);
        var centerRect = centerObj.AddComponent<RectTransform>();
        centerRect.anchorMin = new Vector2(0.5f, 0.5f);
        centerRect.anchorMax = new Vector2(0.5f, 0.5f);
        centerRect.sizeDelta = new Vector2(320, 320);
        centerRect.anchoredPosition = new Vector2(0, 10);

        // 3a. Hào quang Aura
        GameObject auraObj = new GameObject("GlowAura");
        auraObj.transform.SetParent(centerObj.transform, false);
        var auraRect = auraObj.AddComponent<RectTransform>();
        auraRect.sizeDelta = new Vector2(480, 480);
        glowAuraImage = auraObj.AddComponent<Image>();
