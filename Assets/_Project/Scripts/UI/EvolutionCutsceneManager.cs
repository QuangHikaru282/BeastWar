using System;
using System.Collections;
using System.Collections.Generic;
using UnityEngine;
using UnityEngine.UI;
using TMPro;

/// <summary>
/// Quản lý Màn hình & Diễn hoạt Hoạt Ảnh Tiến Hóa (Evolution Cutscene)
/// Chuẩn phong cách Pokémon: Nhấp nháy, phát sáng bùng nổ, biến đổi thành dạng mới.
/// </summary>
public class EvolutionCutsceneManager : MonoBehaviour
{
    private static EvolutionCutsceneManager _instance;
    public static EvolutionCutsceneManager Instance
    {
        get
        {
            if (_instance == null)
            {
                _instance = FindFirstObjectByType<EvolutionCutsceneManager>();
                if (_instance == null)
                {
                    GameObject go = new GameObject("EvolutionCutsceneManager_AutoGenerated");
                    _instance = go.AddComponent<EvolutionCutsceneManager>();
                }
            }
            return _instance;
        }
    }

    [Header("UI Root Elements")]
    [SerializeField] private Canvas cutsceneCanvas;
    [SerializeField] private GameObject panelRoot;
    [SerializeField] private CanvasGroup panelCanvasGroup;

    [Header("Display Elements")]
    [SerializeField] private TextMeshProUGUI titleText;
    [SerializeField] private TextMeshProUGUI messageText;
    [SerializeField] private TextMeshProUGUI continuePromptText;
    [SerializeField] private Image beastImage;
    [SerializeField] private Image whiteSilhouetteImage;
    [SerializeField] private Image glowAuraImage;
    [SerializeField] private Image fullScreenFlash;
    [SerializeField] private Transform sparklesContainer;

    [Header("Audio (Tuỳ chọn)")]
    [SerializeField] private AudioSource audioSource;
    [SerializeField] private AudioClip evolvingMusic;
    [SerializeField] private AudioClip evolvedFanfare;

    private bool _isInitialized = false;
    private bool _isPlaying = false;
    public bool IsPlaying => _isPlaying;

    private void Awake()
    {
        if (_instance != null && _instance != this)
        {
            Destroy(gameObject);
            return;
        }

        _instance = this;
        DontDestroyOnLoad(gameObject);
        InitializeUI();
    }

    /// <summary>
    /// Tự động khởi tạo toàn bộ Canvas và UI nếu chưa được gán sẵn trong Inspector.
    /// </summary>
    private void InitializeUI()
    {
        if (_isInitialized) return;

        if (cutsceneCanvas == null)
        {
            cutsceneCanvas = gameObject.GetComponent<Canvas>();
            if (cutsceneCanvas == null)
            {
                cutsceneCanvas = gameObject.AddComponent<Canvas>();
                cutsceneCanvas.renderMode = RenderMode.ScreenSpaceOverlay;
                cutsceneCanvas.sortingOrder = 999; // Luôn hiển thị trên cùng mọi UI khác

                var scaler = gameObject.AddComponent<CanvasScaler>();
                scaler.uiScaleMode = CanvasScaler.ScaleMode.ScaleWithScreenSize;
                scaler.referenceResolution = new Vector2(1920, 1080);
                scaler.matchWidthOrHeight = 0.5f;

                gameObject.AddComponent<GraphicRaycaster>();
            }
        }

        if (panelRoot == null)
        {
            BuildProceduralUI();
        }

        if (panelRoot != null)
        {
            panelRoot.SetActive(false);
        }

        _isInitialized = true;
    }

    /// <summary>
    /// Tự động dựng giao diện Cutscene chuẩn đẹp mắt
    /// </summary>
